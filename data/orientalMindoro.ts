/* Helper: hanapin ang barangays ng municipality */
export const getBarangaysByMunicipality = (municipalityName: string): string[] => {
  const found = ORIENTAL_MINDORO.find(
    (m) => m.name.toLowerCase() === municipalityName.toLowerCase()
  );
  return found?.barangays || [];
};

/* Helper: lahat ng barangay names para sa search */
export const ALL_BARANGAYS: { municipality: string; barangay: string }[] =
  ORIENTAL_MINDORO.flatMap((m) =>
    m.barangays.map((b) => ({ municipality: m.name, barangay: b }))
  );